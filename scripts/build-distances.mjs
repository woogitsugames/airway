// [task-05] Precompute rounded great-circle kilometres outside the simulation (D-13).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(ROOT, 'src/data/cities.ts'), 'utf8');
const hash = createHash('sha256').update(source).digest('hex');
const outputFile = resolve(ROOT, 'src/data/generated/distances.ts');
const transpiled = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
}).outputText;
const { CITIES } = await import('data:text/javascript;base64,' + Buffer.from(transpiled).toString('base64'));
const EARTH_RADIUS_KM = 6371;
const radians = (degrees) => degrees * Math.PI / 180;

function kilometres(from, to) {
  const dLat = radians(to.lat - from.lat);
  const dLon = radians(to.lon - from.lon);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(radians(from.lat)) *
    Math.cos(radians(to.lat)) * Math.sin(dLon / 2) ** 2;
  return Math.round(EARTH_RADIUS_KM * 2 * Math.asin(Math.min(1, Math.sqrt(a))));
}

const values = [];
for (let high = 1; high < CITIES.length; high++) {
  for (let low = 0; low < high; low++) {
    const distance = kilometres(CITIES[high], CITIES[low]);
    if (distance < 0 || distance > 65535) throw new Error('Distance exceeds uint16 range');
    values.push(distance);
  }
}
const lines = [];
for (let index = 0; index < values.length; index += 20) {
  lines.push('  ' + values.slice(index, index + 20).join(', ') + ',');
}
const codes = CITIES.map((city) => `'${city.code}'`).join(', ');
const content = [
  '// Generated by npm run build:distances. Do not edit by hand.',
  `// Input cities.ts SHA-256: ${hash}`,
  `export const DISTANCE_CITY_COUNT = ${CITIES.length} as const;`,
  `export const DISTANCE_CITY_SHA256 = '${hash}' as const;`,
  `export const DISTANCE_CITY_CODES: readonly string[] = [${codes}];`,
  '// Triangular indexing: row hi starts at hi * (hi - 1) / 2; uint16 suffices for Earth.',
  'const DISTANCES = new Uint16Array([',
  ...lines,
  ']);',
  '',
  'export function distanceKm(a: number, b: number): number {',
  '  if (!Number.isInteger(a) || !Number.isInteger(b) ||',
  '      a < 0 || b < 0 || a >= DISTANCE_CITY_COUNT || b >= DISTANCE_CITY_COUNT) {',
  "    throw new RangeError('City index out of range');",
  '  }',
  '  if (a === b) return 0;',
  '  const hi = a > b ? a : b;',
  '  const lo = a < b ? a : b;',
  '  return DISTANCES[hi * (hi - 1) / 2 + lo];',
  '}',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(outputFile, 'utf8') !== content) {
    console.error('FAIL distance matrix is stale; run npm run build:distances');
    process.exitCode = 1;
  } else {
    console.log(`SUMMARY distances seed=0xA1A1 cities=${CITIES.length} pairs=${values.length} passed=1 failed=0`);
  }
} else {
  writeFileSync(outputFile, content, 'utf8');
  console.log(`SUMMARY distances seed=0xA1A1 cities=${CITIES.length} pairs=${values.length} passed=1 failed=0`);
}
