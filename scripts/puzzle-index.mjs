// [ext-01] R6f, D-160: the puzzle list is derived from the folder, never kept by hand.
// Every `NN.json` in src/data/puzzles is one level; ids are two digits and contiguous from 01 (at most 99).
// `npm run build:puzzles` writes src/data/puzzles/levels.generated.ts from this listing; test:puzzles and
// test:puzzle-packs fail when the committed file is stale.
import { readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const PUZZLE_DIR = resolve(ROOT, 'src/data/puzzles');
export const GENERATED_NAME = 'levels.generated.ts';
export const MAX_PUZZLES = 99;

/** Level ids found in `dir`, in order. Throws on a gap, a non-two-digit level file or more than 99 levels. */
export function puzzleIds(dir = PUZZLE_DIR) {
  const names = readdirSync(dir).filter((name) => name.endsWith('.json'));
  const odd = names.filter((name) => !/^\d{2}\.json$/.test(name));
  if (odd.length) throw new Error(`puzzle files must be named NN.json (two digits): ${odd.join(', ')}`);
  const ids = names.map((name) => name.slice(0, 2)).sort();
  if (!ids.length) throw new Error('no puzzle levels found');
  if (ids.length > MAX_PUZZLES) throw new Error(`at most ${MAX_PUZZLES} puzzles, found ${ids.length}`);
  ids.forEach((id, index) => {
    const want = String(index + 1).padStart(2, '0');
    if (id !== want) throw new Error(`puzzle ids must be contiguous from 01: expected ${want}.json, found ${id}.json`);
  });
  return ids;
}

/** The TypeScript source of the generated index for these ids (deterministic, one import per level). */
export function puzzleIndexSource(ids) {
  const lines = [
    '// Generated by npm run build:puzzles from src/data/puzzles/NN.json (R6f, D-160). Do not edit by hand:',
    '// add a level by adding its NN.json and running `npm run build:puzzles` (build and dev run it too).',
    "import type { PuzzleLevel } from './index.ts';",
    ...ids.map((id) => `import level${id} from './${id}.json';`),
    '',
    '// Runtime validation in startPuzzle rejects malformed JSON at the boundary.',
    'export const PUZZLE_LEVELS: readonly PuzzleLevel[] = [',
  ];
  for (let index = 0; index < ids.length; index += 5) {
    lines.push('  ' + ids.slice(index, index + 5).map((id) => `level${id},`).join(' '));
  }
  lines.push('] as unknown as readonly PuzzleLevel[];', '');
  return lines.join('\n');
}
