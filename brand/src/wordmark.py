# [night-84a] U7, D-339: the Airway lockup, the mark I-1 "Wezel" (D-326, geometry of scripts/icon-assets.mjs) beside the
# word AIRWAY in Archivo 800, width 80 (SIL OFL, the UI-A face, D-336), converted to outlines so the SVGs need no font.
# Run from the repository root (needs fontTools): python3 brand/src/wordmark.py
# Writes brand/wordmark.svg (on its enamel plate: press kit, site hero, Play feature graphic).
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT = 'docs/styles/kierunki-2026-11c/makiety/ui-a/fonts/Archivo-VF.ttf'
ENAMEL, CREAM, YELLOW = '#0E0F0F', '#EFE7D3', '#F3C317'
W, H = 960, 260                     # the press kit renders 1920x520 (site/launch.js PRESS_KIT.logos)
CAP = 110                           # cap height of the word in viewBox units
TRACK = 0.06                        # letter spacing, share of the cap height

font = instantiateVariableFont(TTFont(FONT), {'wght': 800, 'wdth': 80})
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
scale = CAP / font['OS/2'].sCapHeight

# The mark: outer ring r 262 / stroke 44, inner r 176 / 16, bow-tie 12 units at 196 px, on a 1024 tile (D-333).
# The ring's outer edge (r 284 of the tile) is 1.36 cap heights across; the lockup is centred on the plate.
GAP = 40
k = 1.36 * CAP / (2 * 284)
ring_out = 284 * k
word_w = sum(glyphs[cmap[ord(ch)]].width * scale for ch in 'AIRWAY') + CAP * TRACK * 5
left = (W - (2 * ring_out + GAP + word_w)) / 2
def fmt(v): return ('%.2f' % v).rstrip('0').rstrip('.')
cx, cy = left + ring_out, H / 2
mark = (f'<circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(262 * k)}" fill="none" stroke="{CREAM}" stroke-width="{fmt(44 * k)}"/>'
        f'<circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(176 * k)}" fill="none" stroke="{CREAM}" stroke-width="{fmt(16 * k)}"/>'
        f'<path d="M-6 -5.5 L0 0 L-6 5.5Z M6 -5.5 L0 0 L6 5.5Z" fill="{YELLOW}" '
        f'transform="translate({fmt(cx)} {fmt(cy)}) scale({fmt(196 * k / 12)})"/>')

x = cx + ring_out + GAP
baseline = H / 2 + CAP / 2
paths = []
for ch in 'AIRWAY':
    name = cmap[ord(ch)]
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
    paths.append(pen.getCommands())
    x += glyphs[name].width * scale + CAP * TRACK
word_right = x - CAP * TRACK
if word_right > W - 24:
    raise SystemExit(f'word too wide: {word_right:.1f} > {W - 24}')

def svg(plate):
    ground = f'<rect width="{W}" height="{H}" fill="{ENAMEL}"/>' if plate else ''
    word = ''.join(f'<path d="{d}"/>' for d in paths)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
            f'aria-label="Airway">\n<!-- Generated by brand/src/wordmark.py (D-339): mark I-1 and AIRWAY in Archivo 800 '
            f'(SIL OFL) as outlines. -->\n{ground}{mark}<g fill="{CREAM}">{word}</g>\n</svg>\n')

for name, plate in (('brand/wordmark.svg', True),):
    with open(name, 'w') as out:
        out.write(svg(plate))
print(f'wordmark mark {left:.0f}..{cx + ring_out:.0f}, word ..{word_right:.0f} of {W}')
